"""Cut the supplied irregular sprite lists into transparent frames and strips.
Run: python -m pip install Pillow && python scripts/prepare_animation.py
"""
import argparse
from base64 import b64encode
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 192
# Each row contains the gaps between illustrations, not an assumed equal grid.
ROWS = {
    1: [(100, 330, [0, 303, 551, 1000]), (400, 676, [0, 302, 551, 794, 1000])],
    2: [(0, 324, [0, 334, 612, 890, 1179, 1536])],
    3: [(0, 404, [0, 310, 604, 903, 1218, 1536])],
    4: [(0, 340, [0, 353, 712, 990, 1294, 1536]), (340, 642, [0, 352, 620, 943, 1219, 1536])],
    5: [(0, 368, [0, 350, 640, 930, 1217, 1536])],
    6: [(0, 299, [0, 212, 389, 559, 748, 909, 1094, 1358])],
}

def prepare(source_dir):
    manifest = ["// Generated by scripts/prepare_animation.py. Do not edit by hand.", "export default ["]
    target = ROOT / 'assets' / 'animations'
    target.mkdir(parents=True, exist_ok=True)
    for cat, rows in ROWS.items():
        source = Image.open(source_dir / f'cat{cat}_sprite-list.png').convert('RGBA')
        cuts = []
        for top, bottom, boundaries in rows:
            for left, right in zip(boundaries, boundaries[1:]):
                cut = source.crop((left, top, right, bottom))
                # Ignore near-invisible edge pixels when choosing the crop.
                bounds = cut.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
                assert bounds, f'Empty frame: cat {cat}'
                cuts.append(cut.crop(bounds))
        # One scale per cat: no artificial zooming as paws and tails move.
        scale = (SIZE - 16) / max(max(cut.size) for cut in cuts)
        strip = Image.new('RGBA', (SIZE * len(cuts), SIZE))
        frame_dir = target / f'cat{cat}'
        frame_dir.mkdir(exist_ok=True)
        for index, cut in enumerate(cuts):
            cut = cut.resize((max(1, round(cut.width * scale)), max(1, round(cut.height * scale))), Image.Resampling.LANCZOS)
            frame = Image.new('RGBA', (SIZE, SIZE))
            frame.paste(cut, ((SIZE-cut.width)//2, (SIZE-cut.height)//2))
            frame.save(frame_dir / f'{index:02}.png', optimize=True)
            strip.paste(frame, (index * SIZE, 0))
        strip.save(target / f'cat{cat}.png', optimize=True)
        manifest.append('  [')
        for index in range(len(cuts)):
            data = b64encode((frame_dir / f'{index:02}.png').read_bytes()).decode('ascii')
            manifest.append(f'    "data:image/png;base64,{data}",')
        manifest.append('  ],')
        print(f'cat{cat}: {len(cuts)} frames, {strip.width} × {SIZE}')
    manifest.append('];')
    (target / 'frames.js').write_text('\n'.join(manifest) + '\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=Path, default=ROOT / 'cats')
    prepare(parser.parse_args().source)
