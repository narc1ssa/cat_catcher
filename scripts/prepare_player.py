"""Cut man_sprites.png into seven transparent, torso-aligned player poses."""
from base64 import b64encode
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
# Crop box, torso centre. Bottom alignment keeps the waist stationary.
CELLS = [
    ((0, 0, 280, 330), 128), ((280, 0, 550, 330), 397),
    ((550, 0, 840, 330), 655), ((0, 340, 270, 659), 124),
    ((270, 340, 520, 659), 394), ((520, 340, 795, 659), 635),
    ((795, 340, 1073, 659), 939),
]

def prepare():
    source = Image.open(ROOT / 'man_sprites.png').convert('RGBA')
    assert source.size == (1073, 659), 'Unexpected player sheet dimensions'
    target = ROOT / 'assets' / 'animations' / 'player'
    target.mkdir(parents=True, exist_ok=True)
    scale = 1.0
    lines = ['// Generated by scripts/prepare_player.py.', 'export default [']
    for index, (box, anchor) in enumerate(CELLS):
        cut = source.crop(box)
        bounds = cut.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
        assert bounds, f'Empty player pose {index}'
        cut = cut.crop(bounds)
        frame = Image.new('RGBA', (320, 336))
        x = round(160 + (box[0] + bounds[0] - anchor) * scale)
        y = 326 - cut.height
        assert x >= 0 and x + cut.width <= 320 and y >= 0, 'Clipped player pose'
        frame.paste(cut, (x, y))
        frame.save(target / f'{index:02}.png', optimize=True)
        data = b64encode((target / f'{index:02}.png').read_bytes()).decode('ascii')
        lines.append(f'  "data:image/png;base64,{data}",')
    lines.append('];')
    (target / 'frames.js').write_text('\n'.join(lines) + '\n')
    print('Player: 7 aligned frames, 320 × 336')

if __name__ == '__main__':
    prepare()
